"""AIPE-Simulation-Skills adapter: executed ngspice DAB switching simulation.

Runs the Level 1 (ideal) or Level 2 (non-ideal) DAB model through the
``aipe_simulation`` package, stores the waveform dataset and summary as
artifacts, compares the executed result with the analytical SPS reference and
proposes Core simulation/evidence/validation records. The task fails (not
"completes with warnings") when the solver fails or periodic steady state is
not reached.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

from ..engine.envelope import ExecutionEnvelope, now_iso
from ..engine.runner import TaskAdapter, TaskContext


def run_suffix(run_id: str) -> str:
    """Six lowercase hex characters derived from the run id; valid inside Core entity ids."""
    import hashlib

    return hashlib.sha256(run_id.encode('utf-8')).hexdigest()[:6]



class DabNgspiceTask(TaskAdapter):
    id = "aipe.simulation-skills.dab-ngspice"
    version = "0.1.1"

    def requirements(self, environment: dict[str, Any]) -> list[str]:
        problems = []
        try:
            import aipe_simulation  # noqa: F401
        except ImportError:
            problems.append("python package aipe_simulation (AIPE-Simulation-Skills) is not installed: pip install -e ../AIPE-Simulation-Skills")
        tool = environment.get("tools", {}).get("ngspice", {})
        if not tool.get("found"):
            problems.append("ngspice not found (aipe-workflows doctor lists the official download channel)")
        elif tool.get("qualified") is False:
            problems.append("ngspice failed its numerical qualification test")
        return problems

    def execute(self, ctx: TaskContext) -> ExecutionEnvelope:
        from aipe_simulation import __version__ as sim_version
        from aipe_simulation.dab import DabCircuitSpec, run_dab
        from aipe_simulation.ngspice.locate import NgspiceInfo
        from aipe_simulation.waveforms.dab_analysis import compare_with_reference

        started = now_iso()
        p = ctx.task.parameters
        req, conv = ctx.inputs["requirements"], ctx.inputs["converter"]
        analytic = ctx.inputs.get("analytic", {})
        level = int(p.get("level", 1))
        spec = DabCircuitSpec(name=f"{ctx.task.id}", level=level, v1=float(req["input_voltage_V"]), v2=float(req["output_voltage_V"]),
                              f_sw=float(req["switching_frequency_Hz"]), phi_deg=float(analytic.get("phi_deg", conv.get("phase_shift_deg", 22.5))),
                              n_ratio=float(conv["turns_ratio_np_ns"]), l_ext=float(conv.get("external_inductance_H", conv["series_inductance_H"])),
                              l_lk_p=float(conv.get("leakage_inductance_primary_H", 0.0)), l_lk_s=float(conv.get("leakage_inductance_secondary_H", 0.0)),
                              l_m=float(conv.get("magnetising_inductance_H", 1e-3)), r_series_p=float(conv.get("series_resistance_primary_Ohm", 0.02)),
                              r_series_s=float(conv.get("series_resistance_secondary_Ohm", 0.0)), dead_time=float(p.get("dead_time_s", 0.0)))
        for key, value in (p.get("switch") or {}).items():
            setattr(spec.switch, key, value)
        for key, value in (p.get("port2") or {}).items():
            setattr(spec.port2, key, value)
        for key, value in (p.get("dc_link1") or {}).items():
            setattr(spec.dc_link1, key, value)
        for key, value in (p.get("dc_link2") or {}).items():
            setattr(spec.dc_link2, key, value)
        for key, value in (p.get("sim") or {}).items():
            setattr(spec.sim, key, value)
        if p.get("initial_conditions", "analytic") == "analytic" and "i_L_at_centre_origin_A" in analytic:
            spec.sim.use_initial_conditions = True
            spec.sim.initial_series_current = float(analytic["i_L_at_centre_origin_A"])
        spec.notes.append(f"generated by AIPE-Workflows task {ctx.task.id} run {ctx.run_id}")
        tool_info = ctx.environment["tools"]["ngspice"]
        ng = NgspiceInfo(path=tool_info["path"], version=str(tool_info.get("version")), version_output="", source=tool_info.get("source", ""))
        result = run_dab(spec, ctx.task_dir / "ngspice", ngspice=ng)
        envelope = ExecutionEnvelope(task_id=ctx.task.id, task_version=self.version, capability_id="aipe.simulation-skills",
                                     tool={"id": "tool.ngspice", "version": result.run["ngspice_version"], "name": "ngspice"}, status="completed",
                                     started_at=started, finished_at=now_iso(), source_state_id=ctx.state.get("id", ""), source_state_sha256=ctx.state_sha256,
                                     inputs={"circuit_spec": spec.to_dict(), "circuit_spec_sha256": spec.sha256()},
                                     model={"id": f"aipe-dab-ngspice-level{level}", "version": sim_version,
                                            "validity_range": "ideal switches with resistive on-state, E/F ideal transformer with linear magnetising inductance, stiff or RC ports" if level == 1
                                            else "behavioural switches, dead time, linear Coss, DC-link ESR/ESL; no manufacturer device physics"},
                                     environment={"aipe_simulation": sim_version, "ngspice_path": result.run["ngspice_path"], "platform": result.run["platform"]},
                                     evidence_kind="simulation", gate="circuit_simulation")
        run_dir = Path(result.run_dir)
        for name, role, desc in (("circuit.cir", "netlist", "ngspice netlist"), ("circuit.log", "solver_log", "ngspice log"),
                                 ("metadata.json", "model_metadata", "gate timing, switch table, saved vectors"), ("run.json", "run_record", "execution record")):
            if (run_dir / name).is_file():
                envelope.artifacts.append(ctx.artifacts.add(run_dir / name, role, desc, ctx.task.id))
        if not result.succeeded:
            envelope.status = "failed"
            envelope.add_error("solver-failed", "; ".join(result.messages) or "ngspice did not complete")
            return envelope
        envelope.artifacts.append(ctx.artifacts.add(run_dir / "waveforms.h5", "waveform_dataset", "HDF5 waveform dataset with units and provenance", ctx.task.id))
        envelope.artifacts.append(ctx.artifacts.add(run_dir / "summary.json", "waveform_summary", "waveform-derived engineering summary", ctx.task.id))
        summary = result.summary
        if not result.valid:
            envelope.status = "failed"
            envelope.add_error("not-steady-state", summary["steady_state"]["reason"])
            return envelope
        # Compare with the analytical reference where available.
        comparison = None
        if analytic:
            tol = float(p.get("comparison_tolerance", 0.01))
            ref = {"ports.port1.current_avg.value": analytic["i_dc1_A"], "ports.port2.current_avg.value": analytic["i_dc2_A"],
                   "series_path.i_L_rms.value": analytic["i_L_rms_A"], "series_path.i_L_peak_abs.value": analytic["i_L_peak_A"],
                   "ports.port2.power_avg.value": analytic["power_W"]}
            comparison = compare_with_reference(summary, ref, tolerance=tol)
            cpath = ctx.task_dir / "comparison-vs-analytic.json"
            cpath.write_text(json.dumps(comparison, indent=2), encoding="utf-8")
            envelope.artifacts.append(ctx.artifacts.add(cpath, "comparison", "simulated vs analytical SPS quantities", ctx.task.id))
        # Figures (optional matplotlib).
        figures = []
        try:
            from aipe_simulation.waveforms.dataset import WaveformDataset
            from aipe_simulation.waveforms import plots
            ds = WaveformDataset.load_hdf5(run_dir / "waveforms.h5")
            figures.append(plots.plot_dab_overview(ds, summary, ctx.task_dir / "figure-overview.png"))
            figures.append(plots.plot_switch_currents(ds, summary, ctx.task_dir / "figure-switches.png"))
            for fig in figures:
                envelope.artifacts.append(ctx.artifacts.add(fig, "figure", "waveform figure (PNG)", ctx.task.id))
        except Exception as exc:  # plotting is optional
            envelope.add_warning("figure-skipped", f"figures not generated: {type(exc).__name__}: {exc}")
        ports, series, eb = summary["ports"], summary["series_path"], summary["energy_balance"]
        switches = {s["id"]: {"i_rms_A": s["current_rms"]["value"], "i_avg_A": s["current_avg"]["value"],
                              "i_turn_off_mean_abs_A": s["turn_off_current"]["mean_abs_A"], "i_peak_fwd_A": s["current_peak_forward"]["value"],
                              "i_peak_rev_A": s["current_peak_reverse"]["value"], "v_ds_max_V": s["v_ds_max"]["value"],
                              "zvs_current_condition_all_events": s["zvs_current_condition"]["all_events_met"],
                              "conduction_fraction": s["conduction_fraction"]["value"]} for s in summary["switches"]}
        envelope.outputs = {
            "run_dir": str(run_dir), "dataset": str(run_dir / "waveforms.h5"), "dataset_sha256": result.dataset_sha256,
            "summary_path": str(run_dir / "summary.json"), "valid": result.valid, "level": level,
            "p_in_W": ports["port1"]["power_avg"]["value"], "p_out_W": ports["port2"]["power_avg"]["value"],
            "loss_W": ports["loss_total"]["value"], "efficiency": (ports["efficiency"] or {}).get("value"),
            "i_dc1_A": ports["port1"]["current_avg"]["value"], "i_dc2_A": ports["port2"]["current_avg"]["value"],
            "i_L_rms_A": series["i_L_rms"]["value"], "i_L_peak_A": series["i_L_peak_abs"]["value"],
            "i_s_rms_A": series["i_s_rms"]["value"], "i_s_peak_A": series["i_s_peak_abs"]["value"], "i_m_peak_A": series["i_m_peak_abs"]["value"],
            "flux_linkage_pp_Vs": summary["transformer"]["flux_linkage_peak_to_peak"]["value"],
            "measured_phase_shift_deg": summary["bridges"]["measured_phase_shift"].get("phi_deg_mean", {}).get("value"),
            "switches": switches, "zvs_overview": summary["zvs_overview"], "energy_unaccounted_W": eb["p_unaccounted"]["value"],
            "steady_state": {k: summary["steady_state"][k] for k in ("ok", "reason", "periodicity_error", "max_relative_change_in_window", "cycles_in_window")},
            "comparison_vs_analytic": comparison, "figures": figures, "circuit_spec_sha256": spec.sha256(),
        }
        envelope.verification = {
            "periodic_steady_state": summary["steady_state"]["ok"], "periodicity_error": summary["steady_state"]["periodicity_error"],
            "half_wave_antisymmetry_error_i_L": summary["symmetry"]["i_L_half_wave_antisymmetry_error"]["value"],
            "energy_balance_relative_unaccounted": eb["relative_unaccounted"]["value"],
            "volt_second_relative_imbalance": summary["transformer"]["volt_second_relative_imbalance"]["value"],
            "comparison_vs_analytic_pass": comparison["pass"] if comparison else None, "n_solver_warnings": len(result.run.get("warnings", [])),
        }
        for warning in result.run.get("warnings", [])[:5]:
            envelope.add_warning("ngspice", warning)
        # ---- Engineering State proposal ---------------------------------------
        suffix = run_suffix(ctx.run_id)
        tag = ctx.task.id.lower()
        evidence_id = f"evidence.sim-{tag}-{suffix}"
        run_record_id = f"run.ngspice-{tag}-{suffix}"
        check_id = f"check.sim-{tag}-{suffix}"
        analytic_evidence = [analytic["evidence_id"]] if analytic.get("evidence_id") else []
        evidence = {
            "id": evidence_id, "kind": "simulation",
            "description": (f"Executed ngspice {result.run['ngspice_version']} DAB level {level} transient: P_out = {ports['port2']['power_avg']['value']:.1f} W, "
                            f"I_L rms = {series['i_L_rms']['value']:.3f} A, periodic steady state over {summary['window']['cycles']} cycles "
                            f"(periodicity error {summary['steady_state']['periodicity_error']:.2e})."),
            "source": {"type": "repository", "reference": "https://github.com/FulongLi/AIPE-Simulation-Skills", "locator": "src/aipe_simulation/dab"},
            "provenance": {"created_at": started, "activity": "Generate netlist, execute ngspice batch transient, parse raw data, identify steady state and compute waveform metrics.",
                           "tool": {"id": "tool.ngspice", "version": str(result.run["ngspice_version"]), "name": "ngspice"},
                           "skill": {"id": "aipe.simulation-skills.dab", "version": sim_version},
                           "agent": {"id": "aipe.workflows", "version": "0.1.0"}, "inputs": ["evidence.specification", *analytic_evidence]},
            "artifacts": [a.to_core() for a in envelope.artifacts], "review_status": "unreviewed",
        }
        check_pass = bool(result.valid and (comparison is None or comparison["pass"]))
        proposal: dict[str, Any] = {
            "evidence": [evidence],
            "append": [
                {"path": "simulation.runs", "value": {"id": run_record_id, "status": "completed",
                                                      "tool": {"id": "tool.ngspice", "version": str(result.run["ngspice_version"]), "name": "ngspice"},
                                                      "model": next(a.to_core() for a in envelope.artifacts if a.role == "netlist"),
                                                      "outputs": [a.to_core() for a in envelope.artifacts if a.role in ("waveform_dataset", "waveform_summary", "solver_log")],
                                                      "operating_point_ref": "operating-point.nominal", "started_at": started, "completed_at": now_iso(),
                                                      "evidence_refs": [evidence_id]}},
                {"path": "validation.checks", "value": {"id": check_id, "kind": "simulation", "status": "pass" if check_pass else "fail",
                                                        "description": ("Executed level %d DAB simulation reached periodic steady state%s." % (
                                                            level, (f" and matches the analytical SPS reference within {p.get('comparison_tolerance', 0.01):.0%}"
                                                                    if comparison else ""))),
                                                        "evidence_refs": [evidence_id]}},
            ],
            "extensions": {"aipe.workflows.dab": {f"simulation_{tag.replace('-', '_')}": {k: v for k, v in envelope.outputs.items() if k not in ("figures",)}}},
            "status": {"simulation": "completed", "validation": "simulated" if check_pass else "failed"},
            "updated_at": now_iso(),
        }
        envelope.state_proposal = proposal
        if not check_pass:
            envelope.add_error("benchmark-mismatch", "simulation does not match the analytical reference within tolerance")
            envelope.status = "failed"
        return envelope
